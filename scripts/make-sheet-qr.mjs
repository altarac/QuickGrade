import QRCode from 'qrcode';
import {writeFile} from 'node:fs/promises';
const url='https://altarac.github.io/QuickGrade/#scan';
const qr=QRCode.create(url,{errorCorrectionLevel:'M'});
const rows=Array.from({length:qr.modules.size},(_,y)=>Array.from({length:qr.modules.size},(_,x)=>qr.modules.get(y,x)?'1':'0').join(''));
await writeFile('src/utils/sheetQrData.js',`// Generated by npm run qr. Keep the QR matrix bundled so sheets work offline.\nexport const QUICKGRADE_SCAN_URL = ${JSON.stringify(url)};\nexport const SHEET_QR_ROWS = ${JSON.stringify(rows,null,2)};\n`);
console.log(`Generated ${qr.modules.size} × ${qr.modules.size} QR matrix for ${url}`);
